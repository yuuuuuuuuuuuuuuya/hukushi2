def build_default_facilities():
    reader = csv.reader(io.StringIO(ALL_RAW.strip("\n")), delimiter="|")
    merged = {}
    order = []
    for row in reader:
        if len(row) != 6:
            continue
        name, address, phone, cap, org, service = [c.strip() for c in row]
        if not name or not address:
            continue
        try:
            cap_i = int(cap)
        except ValueError:
            cap_i = 0
        key = (name, address)
        if key not in merged:
            merged[key] = {
                "name": name,
                "address": address,
                "phone": phone,
                "capacity": cap_i,
                "org": org,
                "services": [],
            }
            order.append(key)
        rec = merged[key]
        if service not in rec["services"]:
            rec["services"].append(service)
        if cap_i > rec["capacity"]:
            rec["capacity"] = cap_i
        if not rec["phone"] and phone:
            rec["phone"] = phone

    facilities = []
    for key in order:
        rec = merged[key]
        ll = approx_latlon(rec["address"])
        lat, lon = (ll if ll else (None, None))
        facilities.append({
            "id": str(uuid.uuid5(uuid.NAMESPACE_DNS, rec["name"] + "|" + rec["address"])),
            "name": rec["name"],
            "address": rec["address"],
            "phone": rec["phone"],
            "capacity": rec["capacity"],
            "org": rec["org"],
            "services": rec["services"],
            "region": get_region(rec["address"]),
            "is_kofu": "甲府市" in rec["address"],
            "lat": lat,
            "lon": lon,
            "geo_source": "approx",
            "geo_label": "",
        })
    return facilities


